const fs = require("fs");
const path = require("path");

const BLOCKS_DIR = path.resolve(__dirname, "../assets/js/blocks");
const MANIFEST_NAME = "index.js";
const MANIFEST_FILE = path.join(BLOCKS_DIR, MANIFEST_NAME);
const DEFINE_RE = /defineBlock\(\s*(['"`])([^'"`]+)\1/;

const BANNER = "// GENERATED by build/generate-manifest.js - do not edit, your changes will be overwritten.\n\n";

function readBlocks() {
    return fs.readdirSync(BLOCKS_DIR)
        .filter((f) => f.endsWith(".js") && f !== MANIFEST_NAME)
        .sort()
        .map((file) => {
            const src = fs.readFileSync(path.join(BLOCKS_DIR, file), "utf8");
            const match = src.match(DEFINE_RE);

            if (!match) {
                throw new Error(`blocks/${file} does not call defineBlock('<selector>', ...)`);
            }

            return { file, selector: match[2] };
        });
}

function toIdentifier(file) {
    const base = file.replace(/\.js$/, "").replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""));
    return /^[0-9]/.test(base) ? `block${base}` : base;
}

function generateManifest() {
    const blocks = readBlocks();

    const seen = new Map();
    blocks.forEach(({ file, selector }) => {
        if (seen.has(selector)) {
            throw new Error(`duplicate selector "${selector}" in blocks/${file} and blocks/${seen.get(selector)}`);
        }
        seen.set(selector, file);
    });

    const named = blocks.map((block) => ({
        ...block,
        name: toIdentifier(block.file),
    }));

    const names = new Map();
    named.forEach(({ file, name }) => {
        if (names.has(name)) {
            throw new Error(`blocks/${file} and blocks/${names.get(name)} both generate the name "${name}" - rename one`);
        }
        names.set(name, file);
    });

    const out = `${BANNER}${named
        .map(({ file, name }) => `import ${name} from './${file}';`)
        .join("\n")}\n\nexport const BLOCKS = [\n${named
        .map(({ name }) => `    ${name},`)
        .join("\n")}\n];\n`;

    const existing = fs.existsSync(MANIFEST_FILE) ? fs.readFileSync(MANIFEST_FILE, "utf8") : null;
    if (existing !== out) {
        fs.writeFileSync(MANIFEST_FILE, out);
    }

    return blocks.length;
}

module.exports = { generateManifest, MANIFEST_FILE };
